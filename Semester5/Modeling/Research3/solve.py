ROOT = Path(__file__).resolve().parent
OUT = ROOT/'results'
METRICS = ['loss', 'wait', 'sojourn', 'queue', 'utilization', 'number', 'throughput',
           'wait_std', 'sojourn_std', 'wait_cv', 'sojourn_cv', 'zero_wait', 'lost', 'elapsed']
LABELS = {'M':'Экспоненциальный', 'T':'Трасса УИР1', 'H2':'Гиперэкспоненциальный',
          'E2':'Эрланг-2', 'U':'Равномерный'}


def write_csv(name, rows):
    if not rows:
        return
    with (OUT/name).open('w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(dict.fromkeys(k for r in rows for k in r)))
        w.writeheader()
        w.writerows(rows)


def plans(a, cv):
    def config(group, rho, arrival='M', service='M', k=2, capacity=7, **extra):
        return dict(group=group, rho=rho, arrival=arrival, service=service,
                    k=k, capacity=capacity, a=a, b=rho*k*a, arrival_cv=cv, **extra)
    rows = [dict(config('baseline', 2.5), a=2., b=10.)]
    for rho in [.5, .75, .95, .99]:
        for law in ['T', 'H2', 'M', 'U']:
            rows.append(config('arrivals', rho, arrival=law))
        for law in ['M', 'E2', 'H2']:
            rows.append(config('services', rho, service=law))
    for rho in [.5, .9]:
        for capacity in [0, 1, 3, 7, 15, 31, 63, 127, None]:
            rows.append(config('buffer', rho, capacity=capacity))
    for rho in [.5, .75, .95, .99]:
        for k in [1, 2, 3]:
            # А: постоянны a и b, предложенная нагрузка меняется с числом приборов.
            rows.append(dict(config('servers_fixed_work', rho, k=k), b=rho*2*a,
                             rho=rho*2/k, reference_rho=rho))
            # Б: постоянны rho и a; меняется b=rho*k*a.
            rows.append(config('servers_fixed_rho', rho, k=k, reference_rho=rho))
    for rho in [.1, .3, .5, .7, .9]:
        rows.append(config('load', rho))
    for i, row in enumerate(rows):
        row['id'] = f'S{i:03}'
    return rows


def export_gpss(config, trace_cv):
    """Текстовые GPSS World модели; бинарный пример сохранён отдельно."""
    law = config['arrival']
    a, b = config['a'], config['b']
    arrival = {'M':f'(Exponential(20,0,{a:.12g}))',
               'U':f'(Uniform(20,{a/2:.12g},{1.5*a:.12g}))',
               'H2':f'(Hyper(20,{a:.12g},{trace_cv:.12g}))',
               'T':'(GetRandomNumberFromFile("trace.txt"))'}[law]
    service = {'M':f'(Exponential(553,0,{b:.12g}))',
               'E2':f'(Exponential(553,0,{b/2:.12g})+Exponential(554,0,{b/2:.12g}))',
               'H2':f'(Hyper(553,{b:.12g},2))'}[config['service']]
    limit = config['k'] + config['capacity'] if config['capacity'] is not None else None
    lines = [f'* {config["id"]}: {config["group"]}; generated by solve.py.',
             '* Text model for GPSS World. Native translation/run is not verified.',
             '* E is WAITING capacity; total occupancy limit is k+E.',
             '* Finite 120000-arrival cohort is completely drained.',
             '* X$Lost / X$Arrived = loss; Wait/Stay TABLE = cohort statistics.',
             f'Pool STORAGE {config["k"]}',
             'Wait TABLE P1,0,5,400', 'Stay TABLE M1,0,5,400',
             'FilePosition MATRIX ,1,1', 'ErrorCodes MATRIX ,2,1',
             f'        GENERATE {arrival},,,120000',
             '        SAVEVALUE Arrived+,1']
    if limit is not None:
        lines.append(f'        TEST L X$InSystem,{limit},Lost')
    lines += ['        SAVEVALUE InSystem+,1', '        MARK',
              '        QUEUE Buffer', '        ENTER Pool',
              '        ASSIGN 1,M1', '        DEPART Buffer',
              '        TABULATE Wait', f'        ADVANCE {service}',
              '        LEAVE Pool', '        TABULATE Stay',
              '        SAVEVALUE InSystem-,1', '        TERMINATE 1',
              'Lost    SAVEVALUE Lost+,1', '        TERMINATE 1', '',
              'PROCEDURE Hyper(Stream,Mean,CV) BEGIN',
              '    TEMPORARY Prob;',
              '    Prob = (1+SQR((CV#CV-1)/(CV#CV+1)))/2;',
              '    IF (Uniform(Stream,0,1) < Prob) THEN',
              '        RETURN Exponential(Stream,0,Mean/(2#Prob));',
              '    ELSE RETURN Exponential(Stream,0,Mean/(2#(1-Prob)));',
              'END;', '',
              'PROCEDURE GetRandomNumberFromFile(FileName) BEGIN',
              '    TEMPORARY OpenError, CloseError, LineFromFile, FileId;',
              '    FileId = 1;',
              '    OpenError = Open(FileId,FileName);',
              '    IF (OpenError /= 0) THEN BEGIN',
              '        ErrorCodes[1,1] = OpenError;',
              '        RETURN "";',
              '    END;',
              '    FilePosition[1,1] = FilePosition[1,1] + 1;',
              '    Seek(FileId,FilePosition[1,1]);',
              '    LineFromFile = Read(FileId);',
              '    IF (LineFromFile = "") THEN BEGIN',
              '        FilePosition[1,1] = 1;',
              '        Seek(FileId,1);',
              '        LineFromFile = Read(FileId);',
              '    END;',
              '    CloseError = Close(FileId);',
              '    ErrorCodes[2,1] = CloseError;',
              '    RETURN Value(LineFromFile);',
              'END;', '', '        START 120000', '']
    (ROOT/'models'/f'{config["id"]}.gps').write_text('\n'.join(lines), encoding='ascii')


def plot_results(rows):
    plt.rcParams.update({'font.family':'DejaVu Sans', 'font.size':10,
                         'axes.spines.top':False, 'axes.spines.right':False})
    def save(fig, name):
        fig.tight_layout()
        fig.savefig(OUT/f'{name}.svg', bbox_inches='tight')
        fig.savefig(OUT/f'{name}.png', dpi=160, bbox_inches='tight')
        plt.close(fig)
    for group, key, name in [('arrivals','arrival','arrival_laws'),
                             ('services','service','service_laws')]:
        selected = [r for r in rows if r['group'] == group]
        fig, axs = plt.subplots(1, 3, figsize=(12,3.4))
        for law in dict.fromkeys(r[key] for r in selected):
            rr = [r for r in selected if r[key] == law]
            for ax, metric, title in zip(axs, ['wait','sojourn','loss'],
                                         ['Ожидание W, с','Пребывание T, с','Вероятность потери']):
                ax.errorbar([r['rho'] for r in rr], [r[metric] for r in rr],
                            yerr=[r[metric+'_ci'] for r in rr], marker='o', capsize=3,
                            label=LABELS[law])
                ax.set(xlabel='Предложенная нагрузка ρ', ylabel=title)
                ax.grid(alpha=.2)
        axs[0].legend(fontsize=8)
        save(fig, name)
    fig, axs = plt.subplots(1,3,figsize=(12,3.4))
    for rho in [.5,.9]:
        rr = [r for r in rows if r['group']=='buffer' and r['rho']==rho and r['capacity'] is not None]
        for ax,metric,title in zip(axs,['wait','sojourn','loss'],['W, с','T, с','Вероятность потери']):
            ax.plot([r['capacity'] for r in rr], [r[metric] for r in rr], 'o-', label=f'ρ={rho}')
            ax.set(xlabel='Ёмкость очереди E',ylabel=title,xscale='symlog')
            ax.grid(alpha=.2)
    axs[0].legend()
    save(fig,'buffer')
    fig, axs = plt.subplots(1,2,figsize=(10,3.7))
    for ax, group, title in zip(axs,['servers_fixed_work','servers_fixed_rho'],
                               ['Постоянны a и b','Постоянны a и ρ; b=ρka']):
        for rho in [.5,.75,.95,.99]:
            rr=[r for r in rows if r['group']==group and r['reference_rho']==rho]
            ax.plot([r['k'] for r in rr],[r['wait'] for r in rr],'o-',label=f'ρ₂={rho}')
        ax.set(title=title,xlabel='Число приборов k',ylabel='Ожидание W, с',xticks=[1,2,3])
        ax.grid(alpha=.2)
    axs[0].legend(fontsize=8)
    save(fig,'servers')
    fig, axs=plt.subplots(1,2,figsize=(10,3.5))
    rr=[r for r in rows if r['group']=='load']
    for ax,metrics,title in zip(axs,[['rho','utilization'],['wait','sojourn']],
                               ['Предложенная и фактическая загрузка','Временные характеристики']):
        for metric in metrics:
            ax.plot([r['rho'] for r in rr],[r[metric] for r in rr],'o-',label=metric)
        ax.set(title=title,xlabel='Предложенная нагрузка ρ')
        ax.grid(alpha=.2); ax.legend()
    save(fig,'load')


def main(n, repeats):
    OUT.mkdir(exist_ok=True)
    trace=np.loadtxt(ROOT/'input/trace.txt')
    a,cv=float(trace.mean()),float(trace.std(ddof=1)/trace.mean())
    configs=plans(a,cv)
    raw,summary=[],[]
    histograms=[]
    for j,c in enumerate(configs):
        export_gpss(c,cv)
        reps=[]
        for rep in range(repeats):
            result,w,stay=simulate(c,n=n,warmup=20_000,seed=2026000+rep,trace=trace)
            raw.append(dict(id=c['id'],replicate=rep+1,**{m:result[m] for m in METRICS},
                            n=result['n'],accepted=result['accepted']))
            reps.append(result)
            if c['group']=='services' and c['rho']==.95 and rep==0:
                histograms.append((c['service'],w,stay))
        row=dict(c)
        for metric in METRICS:
            values=np.array([r[metric] for r in reps])
            row[metric]=float(values.mean())
            row[metric+'_ci']=float(t.ppf(.975,repeats-1)*values.std(ddof=1)/math.sqrt(repeats))
        summary.append(row)
        if j%10==0:
            print(f'{j+1}/{len(configs)}: {c["group"]}',flush=True)
    # Начальные префиксы и усреднение независимых стартов из пустого состояния.
    checkpoints=[10,50,100,200,300,500,1000,2000,5000,10000,20000]
    transient=[]
    for rho in [.1,.3,.5,.7,.9]:
        for law in ['M','T','H2']:
            c=dict(k=2,capacity=7,a=a,b=2*a*rho,arrival=law,service='M',arrival_cv=cv)
            series={m:[] for m in checkpoints}
            for rep in range(40):
                for count in checkpoints:
                    result,_,_=simulate(c,n=count,warmup=0,seed=300000+rep,trace=trace)
                    series[count].append(result)
            ref=next((r['wait'] for r in summary if r['group']=='load' and r['rho']==rho),None) if law=='M' else None
            # Для T и H2 отдельный прогретый эталон.
            if ref is None:
                ref=np.mean([simulate(c,n=n,warmup=20_000,seed=2026000+r,trace=trace)[0]['wait']
                             for r in range(repeats)])
            for count, rr in series.items():
                values=np.array([r['wait'] for r in rr])
                transient.append(dict(rho=rho,arrival=law,n=count,wait=float(values.mean()),
                                      wait_ci=float(t.ppf(.975,39)*values.std(ddof=1)/math.sqrt(40)),
                                      loss=float(np.mean([r['loss'] for r in rr])),
                                      wait_std=float(np.mean([r['wait_std'] for r in rr])),
                                      sojourn=float(np.mean([r['sojourn'] for r in rr])),
                                      sojourn_std=float(np.mean([r['sojourn_std'] for r in rr])),
                                      reference_wait=float(ref),
                                      deviation_pct=float(100*(values.mean()/ref-1))))
    fig,axs=plt.subplots(1,3,figsize=(12,3.4))
    stabilization=[]
    for ax,law in zip(axs,['M','T','H2']):
        for rho in [.1,.3,.5,.7,.9]:
            rr=[r for r in transient if r['arrival']==law and r['rho']==rho]
            # Практическая точность для малых W: 5% от max(W,1 с).
            tolerance=max(rr[0]['reference_wait'],1)*.05
            settled=next((r['n'] for i,r in enumerate(rr)
                          if all(abs(z['wait']-z['reference_wait'])<=tolerance for z in rr[i:])),None)
            stabilization.append(dict(arrival=law,rho=rho,n=settled,tolerance_seconds=tolerance))
            ax.plot([r['n'] for r in rr],[r['wait']/max(r['reference_wait'],1e-9) for r in rr],
                    'o-',label=f'ρ={rho}',ms=3)
        ax.axhline(1,color='black',lw=.8,ls='--')
        ax.set(xscale='log',xlabel='Поступивших заявок с начала работы',
               ylabel='W префикса / W стационарное',title=LABELS[law],ylim=(0,2))
        ax.grid(alpha=.2)
    axs[0].legend(fontsize=8)
    fig.tight_layout();fig.savefig(OUT/'transient.svg');plt.close(fig)
    plot_results(summary)
    fig,axs=plt.subplots(1,2,figsize=(10,3.6))
    for law,w,stay in histograms:
        for ax,v,title in zip(axs,[w,stay],['Ожидание W, с','Пребывание T, с']):
            # Нормировка по всей выборке, хвост не перенормируется.
            ax.hist(v,bins=np.linspace(0,300,61),weights=np.ones(len(v))/len(v)/5,
                    histtype='step',label=LABELS[law],lw=1.3)
            ax.set(xlabel=title,ylabel='Плотность, с⁻¹')
    axs[0].legend(fontsize=8);fig.tight_layout();fig.savefig(OUT/'histograms.svg');plt.close(fig)
    baseline=summary[0]
    exact=mmke(2,7,2,10)
    research2=json.loads((ROOT/'input/research2.json').read_text())['systems'][0]['metrics']
    aliases={'loss':'total_loss','wait':'total_wait','sojourn':'total_sojourn',
             'queue':'total_queue','throughput':'total_throughput','number':'total_number'}
    comparison=[]
    for metric, expected in exact.items():
        if metric in aliases:
            assert abs(expected-research2[aliases[metric]])<1e-9
        comparison.append(dict(metric=metric,exact=expected,simulation=baseline[metric],
                               ci=baseline[metric+'_ci'],
                               error_pct=100*(baseline[metric]/expected-1)))
        assert abs(baseline[metric]-expected)<max(5*baseline[metric+'_ci'],.025*expected)
    # Независимая проверка бесконечной очереди M/M/1 и формулы Поллачека–Хинчина M/G/1.
    validation=[]
    for law,c2 in [('M',1),('E2',.5),('H2',4)]:
        c=dict(k=1,capacity=None,a=a,b=.5*a,arrival='M',service=law)
        expected=.5*a*(1+c2)/2 # λ E[B²] / (2(1-rho)), rho=.5
        vals=[simulate(c,n=n,warmup=20_000,seed=500000+r,trace=trace)[0]['wait'] for r in range(repeats)]
        mean=float(np.mean(vals));ci=float(t.ppf(.975,repeats-1)*np.std(vals,ddof=1)/math.sqrt(repeats))
        assert abs(mean-expected)<max(5*ci,.04*expected)
        validation.append(dict(service=law,exact_wait=expected,simulation_wait=mean,ci=ci,
                               error_pct=100*(mean/expected-1)))
    buffer_limits=[]
    for rho in [.5,.9]:
        rr=[r for r in summary if r['group']=='buffer' and r['rho']==rho]
        infinite=next(r for r in rr if r['capacity'] is None)
        acceptable=[r for r in rr if r['capacity'] is not None and
                    abs(r['wait']/infinite['wait']-1)<.01 and
                    mmke(2,r['capacity'],a,2*a*rho)['loss']<1e-5]
        zero=[r['capacity'] for r in rr if r['capacity'] is not None and r['lost']==0]
        buffer_limits.append(dict(rho=rho,practical_capacity=min(r['capacity'] for r in acceptable) if acceptable else None,
                                  first_zero_observed=min(zero) if zero else None,
                                  infinite_wait=infinite['wait']))
    data=dict(engine='Independent Python discrete-event simulation; not GPSS REPORT',
              n=n,warmup=20_000,repeats=repeats,confidence=.95,
              trace=dict(n=len(trace),mean=a,cv=cv,h2=h2_parameters(a,cv)),
              experiments=summary,comparison=comparison,validation=validation,
              stabilization=stabilization,buffer_limits=buffer_limits,
              network_variant=None)
    (OUT/'data.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    write_csv('experiments.csv',summary)
    write_csv('replicates.csv',raw)
    write_csv('comparison_research2.csv',comparison)
    write_csv('transient.csv',transient)
    write_csv('stabilization.csv',stabilization)
    write_csv('validation.csv',validation)
    (ROOT/'models/trace.txt').write_text('\n'.join(f'{x:.3f}' for x in trace)+'\n')
    print(f'Готово: {len(configs)} вариантов, {repeats} повторов по {n} заявок.',flush=True)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--n',type=int,default=100_000)
    parser.add_argument('--repeats',type=int,default=8)
    args=parser.parse_args()
    if args.n<1000 or args.repeats<2:
        parser.error('Нужно n >= 1000 и не менее двух независимых повторов')
    self_check()
    main(args.n,args.repeats)
