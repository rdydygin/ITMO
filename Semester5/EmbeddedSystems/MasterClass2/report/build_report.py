def p(text='',style='Normal'):
 x=D.add_paragraph(style=style)
 sample=roles.get(style)
 if sample is not None:
  prop=sample.find(qn('w:pPr'))
  if prop is not None:
   old=x._p.find(qn('w:pPr'))
   if old is not None:x._p.remove(old)
   x._p.insert(0,deepcopy(prop))
 r=x.add_run(text)
 if sample is not None:
  rp=sample.find('.//'+qn('w:rPr'))
  if rp is not None:r._r.insert(0,deepcopy(rp))
 return x

