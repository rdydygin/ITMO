def table(headers,rows):
 elem=deepcopy(source_table)
 tr=elem.findall(qn('w:tr'))
 header=deepcopy(tr[0]);body=deepcopy(tr[1])
 for e in tr:elem.remove(e)
 elem.append(header)
 for _ in rows:elem.append(deepcopy(body))
 D.element.body.insert(len(D.element.body)-1,elem)
 t=Table(elem,D._body)
 for ri,values in enumerate([headers]+rows):
  for cell,value in zip(t.rows[ri].cells,values):
   cp=cell.paragraphs[0]._p
   pp=deepcopy(cp.find(qn('w:pPr')))
   rr=cp.find('.//'+qn('w:rPr'));rr=deepcopy(rr) if rr is not None else None
   for e in list(cp):cp.remove(e)
   if pp is not None:cp.append(pp)
   r=OxmlElement('w:r')
   if rr is not None:r.append(rr)
   tx=OxmlElement('w:t');tx.text=value;r.append(tx);cp.append(r)
 return t

