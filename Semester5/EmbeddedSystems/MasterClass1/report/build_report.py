def diagram(filename, rows):
    im=Image.new('RGB',(1500,180+len(rows)*96),'white'); d=ImageDraw.Draw(im)
    xs=[110,350,600,850,1100,1380]
    names=['SysTick','Процессор\nSTM32C031','GPIOA\nGPIOB','Клавиатура\n4 × 3','TM1637','USART2\nКонсоль']
    for x,n in zip(xs,names):
        d.rectangle((x-100,15,x+100,100),outline='black',width=2)
        d.multiline_text((x,30),n,font=fb,fill='black',anchor='ma',align='center')
        for y in range(110,im.height-20,18): d.line((x,y,x,y+9),fill='#999999',width=2)
    for i,(a,b,t) in enumerate(rows):
        y=170+i*96; xa,xb=xs[a],xs[b]
        if a==b:
            d.line([(xa,y),(xa+80,y),(xa+80,y+23),(xa,y+23)],fill='black',width=3)
            d.polygon([(xa,y+23),(xa+13,y+16),(xa+13,y+30)],fill='black')
            d.text((xa+90,y-4),t,font=f,fill='black')
        else:
            d.line((xa,y+30,xb,y+30),fill='black',width=3)
            sg=1 if xb>xa else -1
            d.polygon([(xb,y+30),(xb-sg*15,y+23),(xb-sg*15,y+37)],fill='black')
            # Wide labels centered above their message line.
            d.text(((xa+xb)/2,y-3),t,font=f,fill='black',anchor='mm')
    im.save(BASE/'assets'/filename)

